-- Angefragtes Datum + Status fuer Booking-Anfragen. status startet immer
-- bei 'angefragt' - Valentin aendert ihn manuell im Table Editor auf
-- 'genehmigt', sobald er zugesagt hat. ERST DANACH traegt er das Event
-- manuell selbst ins oeffentliche Event-Sheet (2026/2027/2028) ein - das
-- bleibt bewusst getrennt, damit auf der Website nie unbestaetigte
-- Anfragen als feste Termine auftauchen.
alter table messages add column if not exists requested_date date;
alter table messages add column if not exists status text not null default 'angefragt';

-- Spalten-genaue Rechte statt der bisherigen ganzen Tabelle: Nutzer
-- duerfen beim Einfuegen NUR dj_slug/message/requested_date setzen, NIE
-- status oder sender_id direkt (die behalten immer ihren serverseitigen
-- Default). Verhindert, dass jemand per direktem API-Aufruf (nicht ueber
-- auth.js) seine eigene Anfrage faelschlicherweise gleich als
-- "genehmigt" markiert.
revoke insert on messages from authenticated;
grant insert (dj_slug, message, requested_date) on messages to authenticated;

-- Oeffentliche Sicht auf genehmigte Buchungen: NUR dj_slug + Datum, keine
-- Nachrichtentexte oder Absender-IDs. Laeuft mit den Rechten des
-- Ersteller-Accounts (Standard-Verhalten von Postgres-Views), umgeht
-- also absichtlich die RLS-Regeln der messages-Tabelle oben - genau
-- dafuer ist diese View da: alle Besucher (auch nicht eingeloggte) duerfen
-- sehen AN WELCHEN Tagen ein DJ schon gebucht ist, aber nichts anderes.
create or replace view public.approved_bookings as
  select dj_slug, requested_date
  from messages
  where status = 'genehmigt' and requested_date is not null;

grant select on public.approved_bookings to anon, authenticated;
