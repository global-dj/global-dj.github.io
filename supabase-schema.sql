-- Migration 2 (2026-10-16): Booking-Kalender pro DJ
-- Einmalig zusaetzlich ausfuehren (SQL Editor -> New query -> Run).
-- Idempotent (IF NOT EXISTS / OR REPLACE), kann gefahrlos mehrfach
-- laufen.
