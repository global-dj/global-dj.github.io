-- Global DJ: Datenbank-Schema fuer das Nachrichten-Feature.
-- Einmalig ausfuehren: Supabase-Dashboard -> SQL Editor -> "New query" ->
-- diesen kompletten Inhalt einfuegen -> "Run".
--
-- Hinweis: Registrierung/Login (Tabelle "auth.users") ist bereits fertig
-- eingebaut in Supabase, dafuer ist nichts zu tun - nur die "messages"-
-- Tabelle fuer die Direktnachrichten an DJs muss angelegt werden.

create table if not exists messages (
  id bigint generated by default as identity primary key,
  -- sender_id wird automatisch von Supabase auf die eingeloggte User-ID
  -- gesetzt (auth.uid()) - kann vom Frontend NICHT gefaelscht werden, da
  -- hier keine Eingabe vom Client akzeptiert wird (siehe auth.js:
  -- gdjSendMessage() schickt sender_id gar nicht erst mit).
  sender_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  dj_slug text not null,
  message text not null check (length(trim(message)) > 0),
  created_at timestamptz not null default now()
);

alter table messages enable row level security;

-- Grund-Tabellenrechte: noetig, weil "Automatically expose new tables"
-- beim Projekt-Setup bewusst ausgeschaltet wurde (Empfehlung von Supabase
-- selbst, Zugriff lieber explizit steuern) - ohne diese GRANTs bekommt
-- die Datenbank "permission denied for table messages", BEVOR die
-- RLS-Regeln unten ueberhaupt greifen (Postgres prueft Tabellenrechte vor
-- Row-Level-Security).
grant insert, select on messages to authenticated;

-- Nur eingeloggte User duerfen Nachrichten einfuegen, und nur mit ihrer
-- eigenen User-ID als Absender (Verteidigung in der Tiefe - zusaetzlich
-- zum serverseitigen Default oben).
create policy "Nutzer koennen eigene Nachrichten einfuegen"
  on messages for insert
  to authenticated
  with check (sender_id = auth.uid());

-- Nutzer koennen nur ihre eigenen gesendeten Nachrichten sehen (z.B. fuer
-- eine spaetere "Gesendet"-Uebersicht), keine fremden.
create policy "Nutzer sehen nur eigene Nachrichten"
  on messages for select
  to authenticated
  using (sender_id = auth.uid());

